-- Q1: exatamente duas tabelas com INNER JOIN. Ocorrências não encerradas e seus trechos.
SELECT o.ID, s.NAME AS TRECHO, o.TYPE, o.SEVERITY, o.STATUS
FROM SR_OCCURRENCE o INNER JOIN SR_SEGMENT s ON s.ID=o.SEGMENT_ID
WHERE o.STATUS <> 'CLOSED' ORDER BY o.ID;

-- Q2: duas tabelas com INNER JOIN e GROUP BY. Quantidade e média das leituras por sensor.
SELECT s.ID, s.NAME, COUNT(l.ID) AS TOTAL_LEITURAS, ROUND(AVG(l.LEVEL_CM),2) AS MEDIA_CM
FROM SR_SENSOR s INNER JOIN SR_READING l ON l.SENSOR_ID=s.ID
GROUP BY s.ID,s.NAME ORDER BY s.ID;

-- Q3: LEFT OUTER JOIN, WHERE e ORDER BY. Preserva trechos acessíveis sem ocorrência ativa.
SELECT s.ID,s.NAME,s.METERS,o.ID AS OCORRENCIA,o.SEVERITY
FROM SR_SEGMENT s LEFT OUTER JOIN SR_OCCURRENCE o
 ON o.SEGMENT_ID=s.ID AND o.STATUS <> 'CLOSED' AND o.VALID_UNTIL>CURRENT_TIMESTAMP
WHERE s.ACCESSIBLE=1
ORDER BY s.METERS,s.ID,o.ID;
