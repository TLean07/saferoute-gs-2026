-- SafeRoute / Oracle 19c+. Apenas objetos SR_. Executar uma vez em namespace livre.
CREATE TABLE SR_REGION (
  ID NUMBER(19) NOT NULL,
  NAME VARCHAR2(100) NOT NULL,
  CITY VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_SR_REGION PRIMARY KEY (ID)
);

CREATE SEQUENCE SR_REGION_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE TABLE SR_POINT (
  ID NUMBER(19) NOT NULL,
  REGION_ID NUMBER(19) NOT NULL,
  NAME VARCHAR2(100) NOT NULL,
  X NUMBER(5) NOT NULL,
  Y NUMBER(5) NOT NULL,
  CONSTRAINT PK_SR_POINT PRIMARY KEY (ID),
  CONSTRAINT FK_POINT_1 FOREIGN KEY (REGION_ID) REFERENCES SR_REGION(ID),
  CONSTRAINT CK_POINT_1 CHECK (X BETWEEN 0 AND 1000),
  CONSTRAINT CK_POINT_2 CHECK (Y BETWEEN 0 AND 1000)
);

CREATE SEQUENCE SR_POINT_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_POINT_1 ON SR_POINT (REGION_ID);

CREATE TABLE SR_SEGMENT (
  ID NUMBER(19) NOT NULL,
  FROM_ID NUMBER(19) NOT NULL,
  TO_ID NUMBER(19) NOT NULL,
  NAME VARCHAR2(100) NOT NULL,
  METERS NUMBER(8) NOT NULL,
  ACCESSIBLE NUMBER(1) NOT NULL,
  LIGHTING NUMBER(1) NOT NULL,
  BLOCKED NUMBER(1) NOT NULL,
  CONSTRAINT PK_SR_SEGMENT PRIMARY KEY (ID),
  CONSTRAINT FK_SEGMENT_1 FOREIGN KEY (FROM_ID) REFERENCES SR_POINT(ID),
  CONSTRAINT FK_SEGMENT_2 FOREIGN KEY (TO_ID) REFERENCES SR_POINT(ID),
  CONSTRAINT CK_SEGMENT_1 CHECK (FROM_ID <> TO_ID),
  CONSTRAINT CK_SEGMENT_2 CHECK (METERS > 0),
  CONSTRAINT CK_SEGMENT_3 CHECK (ACCESSIBLE IN (0,1)),
  CONSTRAINT CK_SEGMENT_4 CHECK (LIGHTING IN (0,1)),
  CONSTRAINT CK_SEGMENT_5 CHECK (BLOCKED IN (0,1))
);

CREATE SEQUENCE SR_SEGMENT_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_SEGMENT_1 ON SR_SEGMENT (FROM_ID);

CREATE INDEX IX_SEGMENT_2 ON SR_SEGMENT (TO_ID);

CREATE TABLE SR_SENSOR (
  ID NUMBER(19) NOT NULL,
  SEGMENT_ID NUMBER(19) NOT NULL,
  NAME VARCHAR2(100) NOT NULL,
  THRESHOLD_CM NUMBER(5) NOT NULL,
  ACTIVE NUMBER(1) NOT NULL,
  CONSTRAINT PK_SR_SENSOR PRIMARY KEY (ID),
  CONSTRAINT FK_SENSOR_1 FOREIGN KEY (SEGMENT_ID) REFERENCES SR_SEGMENT(ID),
  CONSTRAINT CK_SENSOR_1 CHECK (THRESHOLD_CM > 0),
  CONSTRAINT CK_SENSOR_2 CHECK (ACTIVE IN (0,1))
);

CREATE SEQUENCE SR_SENSOR_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_SENSOR_1 ON SR_SENSOR (SEGMENT_ID);

CREATE TABLE SR_READING (
  ID NUMBER(19) NOT NULL,
  SENSOR_ID NUMBER(19) NOT NULL,
  LEVEL_CM NUMBER(6) NOT NULL,
  OBSERVED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_SR_READING PRIMARY KEY (ID),
  CONSTRAINT FK_READING_1 FOREIGN KEY (SENSOR_ID) REFERENCES SR_SENSOR(ID),
  CONSTRAINT CK_READING_1 CHECK (LEVEL_CM >= 0)
);

CREATE SEQUENCE SR_READING_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_READING_1 ON SR_READING (SENSOR_ID);

CREATE TABLE SR_OCCURRENCE (
  ID NUMBER(19) NOT NULL,
  SEGMENT_ID NUMBER(19) NOT NULL,
  TYPE VARCHAR2(20) NOT NULL,
  SEVERITY VARCHAR2(10) NOT NULL,
  STATUS VARCHAR2(12) NOT NULL,
  SOURCE VARCHAR2(12) NOT NULL,
  DESCRIPTION VARCHAR2(500) NOT NULL,
  OBSERVED_AT TIMESTAMP NOT NULL,
  VALID_UNTIL TIMESTAMP NOT NULL,
  CONSTRAINT PK_SR_OCCURRENCE PRIMARY KEY (ID),
  CONSTRAINT FK_OCCURRENCE_1 FOREIGN KEY (SEGMENT_ID) REFERENCES SR_SEGMENT(ID),
  CONSTRAINT CK_OCCURRENCE_1 CHECK (TYPE IN ('FLOOD','OBSTACLE','LIGHTING')),
  CONSTRAINT CK_OCCURRENCE_2 CHECK (SEVERITY IN ('LOW','MEDIUM','HIGH')),
  CONSTRAINT CK_OCCURRENCE_3 CHECK (STATUS IN ('REPORTED','CONFIRMED','CLOSED')),
  CONSTRAINT CK_OCCURRENCE_4 CHECK (SOURCE IN ('SIMULATED','COMMUNITY','OPERATOR')),
  CONSTRAINT CK_OCCURRENCE_5 CHECK (VALID_UNTIL > OBSERVED_AT)
);

CREATE SEQUENCE SR_OCCURRENCE_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_OCCURRENCE_1 ON SR_OCCURRENCE (SEGMENT_ID);

CREATE TABLE SR_ALERT (
  ID NUMBER(19) NOT NULL,
  OCCURRENCE_ID NUMBER(19) NOT NULL,
  MESSAGE VARCHAR2(500) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_SR_ALERT PRIMARY KEY (ID),
  CONSTRAINT FK_ALERT_1 FOREIGN KEY (OCCURRENCE_ID) REFERENCES SR_OCCURRENCE(ID)
);

CREATE SEQUENCE SR_ALERT_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_ALERT_1 ON SR_ALERT (OCCURRENCE_ID);
